import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

import type { CatalogueApi } from '@gym/contracts';

import { WgerExerciseAdapter } from './WgerExerciseAdapter.js';
import type { WgerPage } from './WgerExercise.js';

/**
 * Config injected into `WgerImporter`.
 *
 * `fetchImpl` is injectable for tests. Production code leaves it undefined
 * so the global `fetch` is used.
 */
export interface WgerImporterConfig {
  readonly apiBase: string;
  readonly language: number;
  readonly pageSize: number;
  readonly delayMsBetweenPages: number;
  readonly outputPath: string;
  readonly fetchImpl?: typeof fetch;
}

/**
 * Numbers reported after an import run.
 */
export interface WgerImportSummary {
  readonly totalFetched: number;
  readonly imported: number;
  readonly skippedNoName: number;
  readonly skippedNoLicence: number;
  readonly outputPath: string;
  readonly bytesWritten: number;
}

/**
 * Pulls English exercises from the wger public API, converts each via
 * `WgerExerciseAdapter`, and writes an INSERT OR REPLACE seed file that
 * Wrangler can apply with `wrangler d1 execute --file`.
 *
 * The script is deliberately polite: it paginates serially with a
 * configurable delay between pages, never in parallel.
 */
export class WgerImporter {
  public constructor(private readonly config: WgerImporterConfig) {}

  public async run(): Promise<WgerImportSummary> {
    const fetchFn = this.config.fetchImpl ?? fetch;
    const now = new Date().toISOString();
    const results: CatalogueApi.Exercise[] = [];

    let totalFetched = 0;
    let skippedNoName = 0;
    let skippedNoLicence = 0;
    let offset = 0;
    let hasMore = true;

    while (hasMore) {
      const url = new URL(`${this.config.apiBase}/api/v2/exerciseinfo/`);
      url.searchParams.set('language', String(this.config.language));
      url.searchParams.set('limit', String(this.config.pageSize));
      url.searchParams.set('offset', String(offset));

      const response = await fetchFn(url.toString(), {
        headers: { accept: 'application/json' },
      });
      if (!response.ok) {
        throw new Error(`wger request failed: HTTP ${response.status} for ${url.toString()}`);
      }
      const page = (await response.json()) as WgerPage;
      totalFetched += page.results.length;

      for (const raw of page.results) {
        const result = WgerExerciseAdapter.adapt(raw, now);
        if (result.exercise === null) {
          if (result.skipReason === 'no English name') skippedNoName += 1;
          else if (result.skipReason === 'no licence') skippedNoLicence += 1;
          continue;
        }
        results.push(result.exercise);
      }

      hasMore = page.next !== null && page.results.length > 0;
      offset += this.config.pageSize;

      if (hasMore && this.config.delayMsBetweenPages > 0) {
        await WgerImporter.sleep(this.config.delayMsBetweenPages);
      }
    }

    const bytesWritten = this.writeSeedSql(results);

    return {
      totalFetched,
      imported: results.length,
      skippedNoName,
      skippedNoLicence,
      outputPath: this.config.outputPath,
      bytesWritten,
    };
  }

  private writeSeedSql(exercises: readonly CatalogueApi.Exercise[]): number {
    mkdirSync(dirname(this.config.outputPath), { recursive: true });
    const lines: string[] = [
      '-- Generated by services/catalogue/scripts/importWger.ts',
      '-- Do not edit by hand. Regenerate with: pnpm --filter @gym/catalogue import:wger',
      '-- Each INSERT OR REPLACE statement is idempotent so the seed can be',
      '-- re-applied safely.',
      '',
    ];
    for (const ex of exercises) {
      lines.push(WgerImporter.buildInsertStatement(ex));
    }
    const content = `${lines.join('\n')}\n`;
    writeFileSync(this.config.outputPath, content, 'utf8');
    return Buffer.byteLength(content, 'utf8');
  }

  private static buildInsertStatement(ex: CatalogueApi.Exercise): string {
    const values = [
      WgerImporter.sqlString(ex.id),
      WgerImporter.sqlString(ex.slug),
      WgerImporter.sqlString(ex.name),
      WgerImporter.sqlString(JSON.stringify(ex.muscles)),
      WgerImporter.sqlString(JSON.stringify(ex.equipment)),
      WgerImporter.sqlString(ex.instructions),
      WgerImporter.sqlString(ex.createdAt),
      WgerImporter.sqlString(ex.licence),
      WgerImporter.sqlString(ex.author),
      WgerImporter.sqlString(ex.sourceUrl),
    ];
    return (
      'INSERT OR REPLACE INTO exercises ' +
      '(id, slug, name, muscles, equipment, instructions, createdAt, licence, author, sourceUrl) ' +
      `VALUES (${values.join(', ')});`
    );
  }

  private static sqlString(value: string): string {
    return `'${value.replace(/'/g, "''")}'`;
  }

  private static sleep(ms: number): Promise<void> {
    return new Promise((resolve) => {
      setTimeout(resolve, ms);
    });
  }
}
